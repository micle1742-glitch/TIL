-- 문제 1
SELECT category_code,category_name
FROM tbl_category
WHERE ref_category_code IS NOT NULL
ORDER BY category_name DESC;

SELECT menu_name,menu_price
FROM tbl_menu
WHERE menu_name like '%밥%'
and menu_price BETWEEN 20000 AND 30000;

SELECT *
FROM tbl_menu
WHERE menu_name LIKE '%김치%'
or menu_price < 10000
ORDER BY menu_price ASC,menu_name DESC;

SELECT a.category_name,b.menu_price
FROM tbl_menu b
JOIN tbl_category a 
ON a.category_code = b.category_code
WHERE category_name NOT IN ('기타','쥬스','커피') 
AND b.menu_price = 13000
AND b.orderable_status = 'Y';

