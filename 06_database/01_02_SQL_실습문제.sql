SELECT PHONE,ENT_YN,HIRE_DATE
FROM EMPLOYEE
WHERE ENT_YN = 'N' AND PHONE LIKE '%2'
ORDER BY HIRE_DATE DESC
LIMIT 3;

SELECT JOB_NAME,EMP_NAME,SAL_LEVEL,EMAIL,PHONE
FROM JOB J
JOIN EMPLOYEE E
ON E.JOB_CODE = J.JOB_CODE
WHERE J.JOB_CODE = 'J6'
ORDER BY SAL_LEVEL desc;

SELECT JOB_NAME,EMP_NAME,SAL_LEVEL,EMAIL,PHONE
FROM JOB J, EMPLOYEE E
where E.JOB_CODE = J.JOB_CODE;

SELECT D.DEPT_TITLE,
COUNT(*) AS '부서별 직원수',
SUM(SALARY) AS 급여합계,
AVG(SALARY) AS 급여평균
FROM EMPLOYEE E
JOIN department D
ON E.DEPT_CODE = D.DEPT_ID
WHERE E.ENT_YN = 'N'
GROUP BY D.DEPT_TITLE;

SELECT EMP_NAME,EMP_NO,PHONE,DEPT_TITLE,JOB_NAME,HIRE_DATE
FROM EMPLOYEE E
JOIN DEPARTMENT D
ON E.DEPT_CODE = D.DEPT_ID
JOIN JOB J
ON E.JOB_CODE = J.JOB_CODE
ORDER BY HIRE_DATE ASC;

SELECT
COUNT(*) AS '관리자가있는직원'
FROM EMPLOYEE
