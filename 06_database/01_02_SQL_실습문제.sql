SELECT E.EMP_NAME
FROM EMPLOYEE E
JOIN EMPLOYEE M
    ON E.MANAGER_ID = M.EMP_ID;
    
SELECT E.EMP_NAME, M.EMP_NAME
FROM EMPLOYEE E
LEFT JOIN EMPLOYEE M
ON E.MANAGER_ID = M.EMP_ID
ORDER BY  E.EMP_NAME ASC;

